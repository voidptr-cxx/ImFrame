// ─── Composition macros ──────────────────────────────────────────────────────
//
// These macros require their `glyph` argument to be a string *literal* (or a
// preprocessor macro that expands to one) so C++ adjacent-literal concatenation
// applies at compile time. Pass `ImFrame::Icons::Fa::Home` at runtime instead.

/** @brief  Identity wrapper — marks a string literal as an icon glyph in code. */
#define IMF_ICON(glyph) glyph

/** @brief  Compile-time icon + label: `glyph NBSP NBSP label` as one string literal. */
#define IMF_ICON_LABEL(glyph, label) glyph "\xc2\xa0\xc2\xa0" label

/** @brief  Compile-time label + icon (right-to-left layouts). */
#define IMF_ICON_LABEL_AFTER(label, glyph) label "\xc2\xa0\xc2\xa0" glyph

